function plzCoords(plz) {
  const p = String(plz || '').replace(/\D/g, '');
  if (p.length === 5 && PLZ5[p]) return PLZ5[p];
  if (p.length >= 3 && PLZ3[p.slice(0, 3)]) return PLZ3[p.slice(0, 3)];
  if (p.length >= 2 && PLZ2[p.slice(0, 2)]) return PLZ2[p.slice(0, 2)];
  return null;
}

function estimatePlzDistanceKm(fromPlz, toPlz) {
  const a = plzCoords(fromPlz);
  const b = plzCoords(toPlz);
  if (!a || !b) return null;
  if (String(fromPlz) === String(toPlz)) return 0;
  return haversineKm(a, b);
}

